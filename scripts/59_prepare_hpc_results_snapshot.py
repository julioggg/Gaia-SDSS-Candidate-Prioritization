#!/usr/bin/env python3
"""Prepare a bounded, auditable GitHub snapshot of Jinam experiment outputs.

No GitHub credentials used. Only copies from revision_v2/outputs into
Gaia-SDSS-Candidate-Prioritization/results/hpc_review_snapshot.
Skips symlinks, suspicious paths/extensions, large files and secret-looking
plaintext. Excluded files are recorded in manifest.json. Push via SSH manually.
"""
from pathlib import Path
from datetime import datetime, timezone
import argparse
import hashlib
import json
import re
import shutil

HOME=Path.home()
SOURCE=HOME/"universe_revision/revision_v2/outputs"
DEST=HOME/"Gaia-SDSS-Candidate-Prioritization/results/hpc_review_snapshot"
ALLOWED={".csv",".json",".txt",".tsv",".md",".yaml",".yml",".png",".pdf",".svg",".log",".npz",".npy",".fits",".fit",".parquet"}
BLOCKED={"credentials","secrets",".ssh",".git",".venv","venv","__pycache__","cache"}
BLOCK_WORDS=("private_key","id_rsa","id_ed25519","access_token","api_key","passwd",".pem",".key",".env",".sqlite")
TOKENS=("-----BEGIN PRIVATE KEY-----","-----BEGIN OPENSSH PRIVATE KEY-----",
        "-----BEGIN RSA PRIVATE KEY-----","ghp_","gho_","github_pat_")
MARKER=".generated_by_experiment59"

def sha(path):
 h=hashlib.sha256()
 with path.open("rb") as f:
  for part in iter(lambda:f.read(1<<20),b""):h.update(part)
 return h.hexdigest()

def order(path):
 s=path.as_posix()
 if s.startswith("reviewer_round2/"):return (0,s)
 if s.startswith("external_validation/"):return (1,s)
 if s.startswith("class_specific/") or s.startswith("baseline_reference/"):return (2,s)
 if s.startswith("sensitivity"):return (3,s)
 if s.startswith("logs/"):return (4,s)
 return (5,s)

def safe_text(path,size):
 if path.suffix.lower() not in {".csv",".json",".txt",".tsv",".md",".yaml",".yml",".svg",".log"}:
  return True
 if size>12*1024*1024:return False
 s=path.read_bytes().decode("utf-8",errors="replace")
 if any(m in s for m in TOKENS):return False
 if re.search(r"(?im)^\s*(?:api[_-]?key|access[_-]?token|password|secret[_-]?key)\s*[:=]\s*\S+",s):
  return False
 return True

def main():
 p=argparse.ArgumentParser()
 p.add_argument("--max-file-mb",type=float,default=12.0)
 p.add_argument("--max-total-mb",type=float,default=180.0)
 p.add_argument("--max-files",type=int,default=1800)
 a=p.parse_args()
 if min(a.max_file_mb,a.max_total_mb,a.max_files)<=0:p.error("positive limits required")
 if not SOURCE.is_dir():raise RuntimeError("Missing outputs: "+str(SOURCE))
 if DEST.exists() and not (DEST/MARKER).is_file():
  raise RuntimeError("Destination already exists without ownership marker")
 # Delete only this script-owned snapshot: old intermediate files must not linger.
 if DEST.exists():
  shutil.rmtree(DEST)
 DEST.mkdir(parents=True,exist_ok=True)
 (DEST/MARKER).write_text("Generated by experiment 59 snapshot script\n")
 maxfile=int(a.max_file_mb*1024**2)
 maxtotal=int(a.max_total_mb*1024**2)
 used=0
 n=0
 files=[]
 hashes=[]
 for src in sorted((x for x in SOURCE.rglob("*") if x.is_file() or x.is_symlink()),
                   key=lambda x:order(x.relative_to(SOURCE))):
  rel=src.relative_to(SOURCE)
  name=rel.as_posix()
  row={"path":"outputs/"+name,"bytes":0,"status":"excluded","reason":""}
  if src.is_symlink():row["reason"]="symlink"
  elif "chunks" in (part.lower() for part in rel.parts):row["reason"]="intermediate_batch_chunk"
  elif any(x.lower() in BLOCKED for x in rel.parts):row["reason"]="sensitive_path"
  elif any(x in name.lower() for x in BLOCK_WORDS):row["reason"]="sensitive_filename"
  elif src.suffix.lower() not in ALLOWED:row["reason"]="extension_not_allowed"
  else:
   size=src.stat().st_size
   row["bytes"]=size
   if size>maxfile:row["reason"]="above_file_size_limit"
   elif used+size>maxtotal or n>=a.max_files:row["reason"]="snapshot_budget_exhausted"
   elif not safe_text(src,size):row["reason"]="possible_secret_or_large_text"
   else:
    dst=DEST/"outputs"/rel
    dst.parent.mkdir(parents=True,exist_ok=True)
    shutil.copy2(src,dst)
    value=sha(dst)
    if value!=sha(src):raise RuntimeError("Hash mismatch: "+name)
    row.update({"status":"included","reason":"","sha256":value,
                "snapshot_path":"results/hpc_review_snapshot/outputs/"+name})
    hashes.append(value+"  outputs/"+name)
    used+=size
    n+=1
  files.append(row)
 meta={
  "created_utc":datetime.now(timezone.utc).isoformat(),
  "purpose":"Universe Gaia/SDSS peer-review output snapshot",
  "scope":"revision_v2/outputs only",
  "included_files":n,"excluded_files":len(files)-n,"copied_bytes":used,
  "limits":{"file_mb":a.max_file_mb,"total_mb":a.max_total_mb,"max_files":a.max_files},
  "caveats":[
   "Does not include raw/reference data or all code dependencies",
   "Not evidence of an independent clean-environment rerun",
   "Excluded large files require separate archival storage",
   "Review results and metadata for confidentiality before public push"
  ],
  "files":files
 }
 (DEST/"manifest.json").write_text(json.dumps(meta,indent=2,ensure_ascii=False),encoding="utf-8")
 (DEST/"SHA256SUMS.txt").write_text("\n".join(hashes)+("\n" if hashes else ""),encoding="utf-8")
 (DEST/"README.md").write_text(
  "# Jinam experiment outputs snapshot\n\n"
  "Generated from revision_v2/outputs by script 59.\n\n"
  "Included: "+str(n)+" files, "+format(used/1024**2,".2f")+" MiB.\n\n"
  "Excluded: "+str(len(files)-n)+" files (see manifest.json).\n\n"
  "SHA256SUMS.txt verifies included files. Excluded files are not uploaded.\n"
  "This snapshot is not a complete end-to-end reproducibility package.\n",encoding="utf-8")
 print("Snapshot:",DEST)
 print("Included:",n,"files;",format(used/1024**2,".2f"),"MiB")
 print("Excluded:",len(files)-n)
 for reason in sorted(set(r["reason"] for r in files if r["reason"])):
  print("  ",reason,sum(r["reason"]==reason for r in files))
 print("Review manifest.json and any sensitive results before git push.")

if __name__=="__main__":
 main()
